#!/usr/bin/env bash
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
src="$root/src"
dist="$root/dist"
skill="$dist/learn-topic"
prompt="$dist/learn-topic-prompt.md"

render() {
    awk -v mode="$2" '
        /<!-- skill only -->/  { hidden = (mode != "skill"); next }
        /<!-- prompt only -->/ { hidden = (mode != "prompt"); next }
        /<!-- end -->/         { hidden = 0; next }
        !hidden                { print }
    ' "$1"
}

strip_frontmatter() {
    awk 'BEGIN { fences = 0 }
         /^---$/ { fences++; if (fences <= 2) next }
         fences >= 2 { print }'
}

substitute() {
    local text=$1
    text=${text//@@CURRICULUM_DESIGN_REF@@/"$2"}
    text=${text//@@PROGRESS_TEMPLATE_REF@@/"$3"}
    printf '%s\n' "$text"
}

rm -rf "$dist"
mkdir -p "$skill/references" "$skill/templates"

skill_body=$(render "$src/SKILL.md" skill)
skill_body=$(substitute "$skill_body" '`references/curriculum-design.md`' '`templates/PROGRESS.md`')
printf '%s\n' "$skill_body" > "$skill/SKILL.md"

render "$src/curriculum-design.md" skill > "$skill/references/curriculum-design.md"

for name in TOPIC CURRICULUM PROGRESS; do
    render "$src/templates/$name.md" skill > "$skill/templates/$name.md"
done

body=$(render "$src/SKILL.md" prompt | strip_frontmatter)
body=$(substitute "$body" "the Curriculum design section" "the PROGRESS.md template at the end")

{
    printf '# Learn a topic\n\n'
    printf '<!-- Generated by build.sh from src/. Do not edit. -->\n\n'
    printf '%s\n' "$body"
    printf '\n## Curriculum design\n\n'
    render "$src/curriculum-design.md" prompt
    printf '\n## File templates\n\n'
    for name in TOPIC CURRICULUM PROGRESS; do
        printf '### %s.md\n\n```markdown\n' "$name"
        render "$src/templates/$name.md" prompt
        printf '```\n\n'
    done
} > "$prompt"

printf 'built %s\n' "$skill"
printf 'built %s\n' "$prompt"
